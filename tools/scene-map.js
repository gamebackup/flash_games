#!/usr/bin/env node
/*
    Scene -> island map for the mirror.

    The client requests rooms as "scenes/island<id>/scene<Name>.swf". A room owned by
    the multiuser service arrives with no id of its own, so the path reads
    "scenes/islandundefined/..." and the movie 404s. index.html repairs that path, and
    this table is what tells it which island actually ships the scene.

    Nothing here is transcribed by hand: it is read from games/earlypoptropica/scenes.

    Run it from flash_games/:
      node tools/scene-map.js             summary, plus every name shared by islands
      node tools/scene-map.js --print     the generated table itself
      node tools/scene-map.js --write     regenerate the block in index.html (+ aliases)
                                          and the assets.json file list
      node tools/scene-map.js --check     exit 1 if either one no longer matches disk
*/
"use strict";

const fs = require("fs");
const path = require("path");

const gameDir = path.resolve(__dirname, "..", "games", "earlypoptropica");
const scenesDir = path.join(gameDir, "scenes");
const pageFile = path.join(gameDir, "index.html");

const START = "/* === SCENE MAP (generated by tools/scene-map.js - do not edit by hand) === */";
const END = "/* === end SCENE MAP === */";

// Every name the page is served as. A regenerated map has to land in all of them, or
// one of the old entry points keeps handing out a stale table.
const ALIASES = ["index.htm", "home.htm", "base.html", "base.php/index.html",
                 "index.php/index.html", "error_message.php/index.html"];

function collect() {
    // Only island<Id> folders are reachable through the "scenes/island<Id>/" path the
    // client builds. Global holds event scenes that never load that way, so including
    // it would produce "islandGlobal" paths that cannot exist.
    const dirs = fs.readdirSync(scenesDir).filter(function (name) {
        return /^island/.test(name) && fs.statSync(path.join(scenesDir, name)).isDirectory();
    });

    const map = {},
          skipped = [];

    let files = 0;

    dirs.forEach(function (dir) {
        const id = dir.replace(/^island/, "");

        fs.readdirSync(path.join(scenesDir, dir)).forEach(function (file) {
            if (!/\.swf$/i.test(file)) {
                skipped.push(dir + "/" + file);
                return;
            }

            const scene = file.replace(/\.swf$/i, "").replace(/^scene/, "");

            (map[scene] = map[scene] || []).push(id);
            files++;
        });
    });

    Object.keys(map).forEach(function (scene) { map[scene].sort(); });

    return {
        map: map,
        islands: dirs.map(function (dir) { return dir.replace(/^island/, ""); }).sort(),
        files: files,
        skipped: skipped
    };
}

/*
    Every file the game folder serves, relative to it. assets.json is the list
    tools/check-assets.js walks in the browser to prove a deployment is complete, so it
    is generated here rather than kept by hand.
*/
function manifest() {
    const out = [];

    (function walk(dir, prefix) {
        fs.readdirSync(dir, { withFileTypes: true }).forEach(function (entry) {
            const rel = prefix ? prefix + "/" + entry.name : entry.name;

            if (entry.isDirectory()) return walk(path.join(dir, entry.name), rel);
            if (rel === "assets.json") return;          // the list never describes itself
            out.push(rel);
        });
    })(gameDir, "");

    return out.sort();
}

// One "scene|IslandA,IslandB;" row per scene, wrapped into string-literal chunks so the
// generated block stays readable in the page.
function render(map) {
    const rows = Object.keys(map).sort().map(function (scene) {
        return scene + "|" + map[scene].join(",") + ";";
    });

    const chunks = [];
    let current = "";

    rows.forEach(function (row) {
        if (current && current.length + row.length > 96) {
            chunks.push(current);
            current = "";
        }

        current += row;
    });

    if (current) chunks.push(current);

    const body = chunks.length
        ? chunks.map(function (chunk, index) {
              return "        " + JSON.stringify(chunk) + (index < chunks.length - 1 ? " +" : ";");
          }).join("\n")
        : "        \"\";";

    return START + "\n    const SCENE_MAP =\n" + body + "\n    " + END;
}

function parse(block) {
    const map = {},
          body = block.slice(block.indexOf("=") + 1, block.lastIndexOf(END));

    (body.match(/"(?:[^"\\]|\\.)*"/g) || []).forEach(function (literal) {
        JSON.parse(literal).split(";").forEach(function (row) {
            const parts = row.split("|");

            if (parts.length === 2 && parts[0]) map[parts[0]] = parts[1].split(",");
        });
    });

    return map;
}

function currentBlock(page) {
    const start = page.indexOf(START),
          end = page.indexOf(END);

    if (start === -1 || end === -1) return null;

    return page.slice(start, end + END.length);
}

function summary(data) {
    const scenes = Object.keys(data.map);
    const shared = scenes.filter(function (scene) { return data.map[scene].length > 1; });

    console.log("islands: " + data.islands.length + "  scenes: " + data.files + "  distinct names: " + scenes.length);
    console.log("islands: " + data.islands.join(" "));

    if (data.skipped.length) console.log("non-swf entries skipped: " + data.skipped.length + " (" + data.skipped.slice(0, 5).join(", ") + ")");

    console.log("names in more than one island: " + shared.length + " / " + scenes.length);

    if (shared.length) {
        shared.slice(0, 12).forEach(function (scene) {
            console.log("  " + scene + " -> " + data.map[scene].join(", "));
        });

        if (shared.length > 12) console.log("  ... " + (shared.length - 12) + " more");
    }
}

const args = process.argv.slice(2),
      data = collect(),
      rendered = render(data.map),
      page = fs.readFileSync(pageFile, "utf8"),
      block = currentBlock(page);

if (args.indexOf("--check") > -1) {
    if (!block) {
        console.error("scene map markers are missing from index.html");
        process.exit(1);
    }

    if (block !== rendered) {
        console.error("index.html scene map is out of date - run: node tools/scene-map.js --write");
        process.exit(1);
    }

    let saved = null;
    try { saved = JSON.parse(fs.readFileSync(path.join(gameDir, "assets.json"), "utf8")); } catch (err) { }

    if (!saved || JSON.stringify(saved.files) !== JSON.stringify(manifest())) {
        console.error("assets.json is out of date - run: node tools/scene-map.js --write");
        process.exit(1);
    }

    console.log("scene map is up to date (" + Object.keys(data.map).length + " scenes, " + manifest().length + " files)");
    process.exit(0);
}

if (args.indexOf("--write") > -1) {
    if (!block) {
        console.error("scene map markers are missing from index.html");
        process.exit(1);
    }

    const before = parse(block),
          after = data.map,
          added = Object.keys(after).filter(function (scene) { return !before[scene]; }),
          removed = Object.keys(before).filter(function (scene) { return !after[scene]; });

    // Function form: a replacement string would treat "$" in a scene name as a
    // substitution pattern and silently corrupt the page.
    const next = page.replace(block, function () { return rendered; });

    fs.writeFileSync(pageFile, next);

    ALIASES.forEach(function (alias) {
        const file = path.join(gameDir, alias);

        if (fs.existsSync(file)) fs.writeFileSync(file, next);
    });

    const assets = manifest();

    fs.writeFileSync(path.join(gameDir, "assets.json"), JSON.stringify({ files: assets }));

    console.log("wrote " + Object.keys(after).length + " scenes into index.html and " + ALIASES.length + " aliases");
    console.log("wrote " + assets.length + " files into assets.json");
    if (added.length) console.log("  added: " + added.slice(0, 10).join(", ") + (added.length > 10 ? " ..." : ""));
    if (removed.length) console.log("  removed: " + removed.slice(0, 10).join(", ") + (removed.length > 10 ? " ..." : ""));

    process.exit(0);
}

if (args.indexOf("--print") > -1) {
    console.log(rendered);
    process.exit(0);
}

summary(data);
console.log("");
console.log("next: node tools/scene-map.js --write   (regenerate the page)");
